"""Build ``(query, positive_text)`` training pairs from the catalog.

Two strategies, both grounded in the catalog so no external labels are needed:

- :func:`build_proxy_pairs` — deterministic, offline. Derives query-like anchors
  from a course's own fields (title, skills, category). No network, no LLM.
- :func:`build_llm_pairs` — synthetic queries generated by an LLM for each course
  (InPars / "query generation" style). Higher quality, needs an LLM provider.

Each pair is ``{"query": str, "positive": str, "course_id": Any, "strategy": str}``.
``positive`` is the full course text the retriever should match the query to.
Pairs feed ``sentence_transformers.losses.MultipleNegativesRankingLoss``, which
treats every other positive in a batch as an in-batch negative, so no explicit
negatives are required.
"""
from __future__ import annotations

import json
from collections.abc import Callable, Iterable
from typing import Any

# A text-completion callable: (system, prompt) -> model text. Matches
# ``LLMProvider.complete`` when wrapped, and is trivial to fake in tests.
Complete = Callable[[str, str], str]

_QUERY_SYSTEM = (
    "You generate short, natural search queries a learner would type into a "
    "course-search box to find a specific online course. Output only the "
    "queries, one per line, no numbering, no quotes, no extra text."
)


def _clean(value: Any) -> str:
    """Normalise a possibly-missing cell to a trimmed string."""
    if value is None:
        return ""
    text = str(value).strip()
    return "" if text.lower() in ("", "nan", "none") else text


def course_text(record: dict) -> str:
    """The full text a query should match to — title, skills, description, etc."""
    parts = [
        _clean(record.get("title")),
        _clean(record.get("skills")),
        _clean(record.get("description")),
        _clean(record.get("category")),
        _clean(record.get("level")),
    ]
    return ". ".join(p for p in parts if p)


def build_proxy_pairs(records: Iterable[dict]) -> list[dict]:
    """Deterministic pairs from each course's own fields (no LLM, no network).

    Produces a few short, query-like anchors per course (its title, its skills,
    and a "learn <skills>" phrasing), each pointing at the full course text. Weak
    supervision, but a sane baseline that always runs — useful for CI and as a
    fallback when no LLM is configured.
    """
    pairs: list[dict] = []
    for rec in records:
        positive = course_text(rec)
        if not positive:
            continue
        cid = rec.get("id")
        title, skills = _clean(rec.get("title")), _clean(rec.get("skills"))
        category = _clean(rec.get("category"))

        anchors = set()
        if title:
            anchors.add(title)
        if skills:
            anchors.add(skills)
            anchors.add(f"learn {skills}")
        if category and title:
            anchors.add(f"{category} course on {title}")

        for q in anchors:
            pairs.append({"query": q, "positive": positive, "course_id": cid, "strategy": "proxy"})
    return pairs


def _parse_queries(text: str, limit: int) -> list[str]:
    """Pull clean query lines out of an LLM completion."""
    out: list[str] = []
    for raw in text.splitlines():
        # strip a leading bullet/number prefix first, then surrounding quotes
        line = raw.strip().lstrip("-•*0123456789.) ").strip().strip("\"'").strip()
        if len(line) >= 3 and line not in out:
            out.append(line)
        if len(out) >= limit:
            break
    return out


def build_llm_pairs(
    records: Iterable[dict],
    complete: Complete,
    *,
    per_course: int = 3,
    max_tokens: int = 160,
) -> list[dict]:
    """Synthetic query pairs: ask an LLM for realistic queries per course.

    ``complete(system, prompt)`` returns the model's text (wrap
    ``LLMProvider.complete`` to supply it). A course that yields no usable query
    is skipped rather than fabricated.
    """
    pairs: list[dict] = []
    for rec in records:
        positive = course_text(rec)
        if not positive:
            continue
        prompt = (
            f"Course title: {_clean(rec.get('title')) or 'n/a'}\n"
            f"Skills: {_clean(rec.get('skills')) or 'n/a'}\n"
            f"Category: {_clean(rec.get('category')) or 'n/a'}\n"
            f"Level: {_clean(rec.get('level')) or 'n/a'}\n\n"
            f"Write {per_course} diverse, realistic search queries (3-10 words each) "
            "a learner might type to find THIS course. One per line."
        )
        try:
            text = complete(_QUERY_SYSTEM, prompt)
        except Exception:
            continue  # one bad course never aborts the whole run
        for q in _parse_queries(text, per_course):
            pairs.append({"query": q, "positive": positive, "course_id": rec.get("id"), "strategy": "llm"})
    return pairs


def write_jsonl(pairs: Iterable[dict], path: str) -> int:
    """Write pairs as JSON Lines (creating parent dirs); return the number written."""
    import os

    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    n = 0
    with open(path, "w", encoding="utf-8") as f:
        for p in pairs:
            f.write(json.dumps(p, ensure_ascii=False) + "\n")
            n += 1
    return n


def read_jsonl(path: str) -> list[dict]:
    """Read pairs back from a JSON Lines file."""
    pairs: list[dict] = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                pairs.append(json.loads(line))
    return pairs
